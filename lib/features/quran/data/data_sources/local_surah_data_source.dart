/// Local Surah Data Source
///
/// Handles reading and parsing Quran surah metadata from local assets
class LocalSurahDataSource {
  /// Load all Surahs metadata from local asset file
  ///
  /// Returns: Future<List<SurahModel>>
  /// Throws: Exception if the file cannot be read or parsed
  Future<List<SurahModel>> loadAllSurahs() async {
    try {
      // Read the surah metadata from assets
      final jsonString = await rootBundle.loadString(
        'assets/surah_metadata.json',
      );
      final List<dynamic> jsonData = jsonDecode(jsonString);

      final surahs = <SurahModel>[];

      for (final item in jsonData) {
        final surah = SurahModel.fromJson(item as Map<String, dynamic>);
        surahs.add(surah);
      }

      return surahs;
    } catch (e) {
      // If the metadata file doesn't exist, generate from known Quran data
      return _generateSurahMetadata();
    }
  }

